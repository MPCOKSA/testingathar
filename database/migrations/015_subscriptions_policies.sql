CREATE TABLE IF NOT EXISTS subscription_plans (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    slug TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    price_minor INTEGER NOT NULL DEFAULT 0 CHECK(price_minor>=0),
    currency TEXT NOT NULL DEFAULT 'SAR',
    duration_days INTEGER NOT NULL DEFAULT 30 CHECK(duration_days BETWEEN 1 AND 3650),
    max_evidence INTEGER NOT NULL DEFAULT 24 CHECK(max_evidence BETWEEN 0 AND 10000),
    max_sections INTEGER NOT NULL DEFAULT 24 CHECK(max_sections BETWEEN 1 AND 100),
    ai_enabled INTEGER NOT NULL DEFAULT 1 CHECK(ai_enabled IN (0,1)),
    custom_templates_enabled INTEGER NOT NULL DEFAULT 1 CHECK(custom_templates_enabled IN (0,1)),
    public_sharing_enabled INTEGER NOT NULL DEFAULT 1 CHECK(public_sharing_enabled IN (0,1)),
    file_upload_enabled INTEGER NOT NULL DEFAULT 1 CHECK(file_upload_enabled IN (0,1)),
    is_active INTEGER NOT NULL DEFAULT 1 CHECK(is_active IN (0,1)),
    sort_order INTEGER NOT NULL DEFAULT 0,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS user_subscriptions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    plan_id INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','cancelled','expired')),
    starts_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ends_at TEXT NULL,
    admin_note TEXT NOT NULL DEFAULT '',
    created_by INTEGER NULL,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY(plan_id) REFERENCES subscription_plans(id) ON DELETE RESTRICT,
    FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_user_subscriptions_user ON user_subscriptions(user_id,status,ends_at,created_at DESC);
CREATE TABLE IF NOT EXISTS site_policies (
    policy_key TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    body TEXT NOT NULL DEFAULT '',
    version INTEGER NOT NULL DEFAULT 1,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS policy_acceptances (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    user_id INTEGER NOT NULL,
    policy_key TEXT NOT NULL,
    version INTEGER NOT NULL,
    accepted_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY(policy_key) REFERENCES site_policies(policy_key) ON DELETE CASCADE,
    UNIQUE(user_id,policy_key,version)
);
CREATE INDEX IF NOT EXISTS idx_policy_acceptance_user ON policy_acceptances(user_id,policy_key,version);
